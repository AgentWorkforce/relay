#!/usr/bin/env python3
"""Generate native vector paths from the canonical, vendored website wordmark.

To update: copy agentrelay.com/web/public/brand-kit/agent-relay-wordmark.svg
into assets/agent-relay-wordmark.svg, then run this script.
"""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parent.parent
svg = ET.parse(root / "assets/agent-relay-wordmark.svg").getroot()
viewbox = svg.attrib["viewBox"].split()
paths = []
for element in svg:
    if not element.tag.endswith("}path"):
        raise ValueError("Unsupported wordmark element")
    tokens = re.findall(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?", element.attrib["d"])
    index = 0
    x = y = "0"
    start = (x, y)
    commands = []
    while index < len(tokens):
        command = tokens[index]
        index += 1
        count = {"M": 2, "L": 2, "C": 6, "H": 1, "V": 1, "Z": 0}[command]
        values = tokens[index:index + count]
        index += count
        if command == "H":
            x = values[0]
            commands.append(f"L{x} {y}")
        elif command == "V":
            y = values[0]
            commands.append(f"L{x} {y}")
        else:
            commands.append(command + " ".join(values))
            if command == "Z":
                x, y = start
            else:
                x, y = values[-2:]
                if command == "M":
                    start = (x, y)
    paths.append("".join(commands))
assert len(paths) == 1, "Expected the canonical single-path wordmark"
output = f'''// Generated by scripts/generate-wordmark.py from assets/agent-relay-wordmark.svg.
// Source: agentrelay.com/web/public/brand-kit/agent-relay-wordmark.svg.
// Geometry is unchanged; absolute H/V segments are expanded to L for SVGPath.
import CoreGraphics
import RelayDesktopCore

enum BrandWordmarkPaths {{
    static let viewBox = CGRect(x: {viewbox[0]}, y: {viewbox[1]}, width: {viewbox[2]}, height: {viewbox[3]})
    static let commands = try! SVGPath.parse("{paths[0]}")
}}
'''
(root / "macos/Sources/RelayDesktop/BrandWordmarkPaths.swift").write_text(output)
