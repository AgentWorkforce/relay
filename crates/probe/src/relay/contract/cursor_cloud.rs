//! Cursor Cloud Agents managed through Agent Relay Cloud.
//!
//! Cursor credentials stay in Cloud. The desktop contract carries only
//! workspace-scoped agent, run and relay-binding state.

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudModel {
    pub id: String,
    pub display_name: String,
    pub description: Option<String>,
    pub is_default: Option<bool>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudModels {
    pub models: Vec<CursorCloudModel>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRepositories {
    pub repositories: Vec<CursorCloudRepository>,
    pub cached_at: String,
    pub stale: bool,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRepository {
    pub url: String,
    pub starting_ref: Option<String>,
    pub pull_request_url: Option<String>,
}

/// A repository requested for a new Cloud Agent. Kept separate from the
/// result shape so Swift can encode omitted provider options correctly.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRepositoryInput {
    pub url: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub starting_ref: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub pull_request_url: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudBinding {
    /// `pending`, `bound`, or `unbound`.
    pub state: String,
    /// The Relay agent name once the Cloud Agent is registered.
    pub agent: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudAgent {
    pub id: String,
    pub name: String,
    /// Cursor's durable agent state: `ACTIVE`, `IDLE`, or `ARCHIVED`.
    pub status: String,
    pub url: String,
    pub created_at: String,
    pub updated_at: String,
    pub latest_run_id: Option<String>,
    #[serde(default)]
    pub repositories: Vec<CursorCloudRepository>,
    pub binding: CursorCloudBinding,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudAgentsListParams {
    pub cursor: Option<String>,
    pub limit: Option<u16>,
    pub include_archived: Option<bool>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudAgents {
    pub agents: Vec<CursorCloudAgent>,
    pub next_cursor: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRepositoryFile {
    pub url: String,
    pub path: String,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudEnvironment {
    pub id: String,
    pub name: Option<String>,
    pub owner: String,
    #[serde(default)]
    pub repositories: Vec<CursorCloudRepository>,
    pub created_at: String,
    pub updated_at: String,
    pub repository_file: Option<CursorCloudRepositoryFile>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudEnvironmentsListParams {
    pub query: Option<String>,
    pub owner: Option<String>,
    pub named: Option<bool>,
    #[serde(default)]
    pub repo: Vec<String>,
    pub user_id: Option<String>,
    pub cursor: Option<String>,
    pub limit: Option<u16>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudEnvironments {
    pub environments: Vec<CursorCloudEnvironment>,
    pub next_cursor: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudAgentSpawnParams {
    /// Durable idempotency key generated by the caller and reused on retry.
    pub client_request_id: String,
    pub task: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    #[serde(default)]
    pub repositories: Vec<CursorCloudRepositoryInput>,
    /// A Cursor model id returned by `cursor_cloud.models.list`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub model: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub environment: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub work_on_current_branch: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub auto_create_pull_request: Option<bool>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudAgentParams {
    pub agent_id: String,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum CursorCloudDelivery {
    /// Add the prompt to the running turn, or queue it as the next run.
    #[default]
    Steer,
    /// Start a new run and fail if the agent is already busy.
    Run,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRunCreateParams {
    pub agent_id: String,
    pub client_request_id: String,
    pub task: String,
    /// Omit for `steer`, which injects now or queues the next run.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub delivery: Option<CursorCloudDelivery>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRunParams {
    pub agent_id: String,
    pub run_id: String,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRunsListParams {
    pub agent_id: String,
    pub cursor: Option<String>,
    pub limit: Option<u16>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudGitBranch {
    pub repository_url: String,
    pub branch: Option<String>,
    pub pull_request_url: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRun {
    pub id: Option<String>,
    pub agent_id: String,
    /// Cursor run state, or `STEERED` / `QUEUED` for an injected follow-up.
    pub status: String,
    pub created_at: Option<String>,
    pub updated_at: Option<String>,
    pub duration_ms: Option<u64>,
    pub result: Option<String>,
    #[serde(default)]
    pub branches: Vec<CursorCloudGitBranch>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudRuns {
    pub runs: Vec<CursorCloudRun>,
    pub next_cursor: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct CursorCloudLifecycle {
    pub agent_id: String,
    pub status: String,
    pub binding: CursorCloudBinding,
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn spawn_omits_no_provider_credential_and_keeps_idempotency() {
        let request: CursorCloudAgentSpawnParams = serde_json::from_value(json!({
            "client_request_id": "operation-1",
            "task": "Fix the failing test",
            "repositories": [{"url": "https://github.com/example/repo", "starting_ref": "main", "pull_request_url": null}],
            "name": null,
            "model": null,
            "environment": null,
            "work_on_current_branch": null,
            "auto_create_pull_request": true
        }))
        .unwrap();
        let value = serde_json::to_value(request).unwrap();
        assert_eq!(value["client_request_id"], "operation-1");
        assert!(value.get("api_key").is_none());
        assert!(value.get("credential").is_none());
    }

    #[test]
    fn omitted_follow_up_delivery_uses_the_cloud_steer_default() {
        let request: CursorCloudRunCreateParams = serde_json::from_value(json!({
            "agent_id": "bc-agent", "client_request_id": "message-1", "task": "Check the error path"
        }))
        .unwrap();
        assert_eq!(request.delivery, None);
    }

    #[test]
    fn idless_steer_acknowledgement_decodes() {
        let run: CursorCloudRun = serde_json::from_value(json!({
            "id": null,
            "agent_id": "bc-agent",
            "status": "QUEUED",
            "created_at": null,
            "updated_at": null,
            "duration_ms": null,
            "result": null,
            "branches": []
        }))
        .unwrap();
        assert_eq!(run.id, None);
        assert_eq!(run.agent_id, "bc-agent");
        assert_eq!(run.status, "QUEUED");
    }
}
